  /**
   * Generates TestRail Cases import CSV (testrail-cases-import.csv)
   */
  public generateTestRailCsv(state: CompiledSdlcState): string {
    const rtmRows = state.rtmRows || [];
    const rows: string[] = [];
    rows.push('"Title","Section","Preconditions","Steps","Expected Result","Type","Priority"');

    rtmRows.forEach((r) => {
      const title = `[${r.testId}] ${r.testTitle}`.replace(/"/g, '""');
      const section = (r.moduleName || 'Core Feature').replace(/"/g, '""');
      const pre = `User authenticated with valid session role. Navigated to route ${r.pagePath || '/'}`.replace(/"/g, '""');
      const steps = `1. Open ${r.pagePath || '/'}\\n2. Resolve locator: ${(r.selfHealingLocatorChain || []).slice(0, 2).join(' -> ')}\\n3. Execute scenario assertion`.replace(/"/g, '""');
      const expected = r.expectedOutcome.replace(/"/g, '""');
      const prio = r.executionPriorityTier === 'P0_CRITICAL_SMOKE' ? 'Critical' : r.executionPriorityTier === 'P1_CORE_REGRESSION' ? 'High' : 'Medium';
      rows.push(`"${title}","${section}","${pre}","${steps}","${expected}","Automated","${prio}"`);
    });

    return rows.join('\r\n');
  }

